# Compile the ELE-written multi-function CFG backend with the temporary Stage 0.
# The backend emits a Linux ELF64 binary directly with writeBytes.
param(
    [string]$Lir = 'examples/native_cfg_loop_call.lir',
    [string]$Output = 'target/native-ele/ele-cfg.elf'
)
$ErrorActionPreference = 'Stop'
$env:RUSTUP_TOOLCHAIN = 'stable-x86_64-pc-windows-msvc'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$work = Join-Path $root 'target/native-ele-cfg'
[IO.Directory]::CreateDirectory($work) > $null
Push-Location $root
try {
    cargo build -p project-l --target x86_64-pc-windows-msvc
    if ($LASTEXITCODE -ne 0) { throw 'Cannot compile Stage 0' }
} finally { Pop-Location }
$stage0 = Join-Path $root 'target/x86_64-pc-windows-msvc/debug/l.exe'
$source = Join-Path $root 'compiler-l/src/native_cfg_demo.l'
$inputFile = (Resolve-Path (Join-Path $root $Lir)).Path
$dest = [IO.Path]::GetFullPath((Join-Path $root $Output))
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($dest)) > $null
Push-Location $work
try {
    $lines = & $stage0 build $source --backend cranelift
    if ($LASTEXITCODE -ne 0) { throw 'Stage 0 failed to compile ELE-written backend' }
    $line = $lines | Where-Object { $_ -like 'Build: *' } | Select-Object -First 1
    if (-not $line) { throw 'Missing Build: output' }
    $exe = (Resolve-Path $line.Substring(7)).Path
    & $exe $inputFile $dest
    if ($LASTEXITCODE -ne 0) { throw 'ELE-written native CFG backend rejected the LIR or failed to write ELF' }
    $bytes = [IO.File]::ReadAllBytes($dest)
    if ($bytes.Length -le 4096 -or $bytes[0] -ne 127 -or $bytes[1] -ne 69 -or $bytes[2] -ne 76 -or $bytes[3] -ne 70) {
        throw 'Invalid ELF64 output'
    }
    Write-Output "Generated by ELE-written x86-64 backend: $dest ($($bytes.Length) bytes)"
    Write-Output 'Run on Linux x86-64/WSL. Expected exit code: 8.'
} finally { Pop-Location }
